import { scrypt as scryptCallback, timingSafeEqual } from 'node:crypto';
import { promisify } from 'node:util';
const scrypt = promisify(scryptCallback);
const stored = 'scrypt$16384$8$1$UKtKscCdZNkW_s5Ro9aAHQ$6DYciZ4A03zvSRwJTNTagGcAO9vJkSt0CxeXHZJCSk2yx1vp58Xw2pFnXyRWSVcczdq2FYghYGyBibpyjn9XAA';
const [scheme, N, r, p, saltValue, hashValue] = stored.split('$');
const expected = Buffer.from(hashValue, 'base64url');
const derived = await scrypt('123456789', Buffer.from(saltValue, 'base64url'), expected.length, { N: Number(N), r: Number(r), p: Number(p), maxmem: 128 * 1024 * 1024 });
console.log('length match:', derived.length === expected.length);
console.log('timingSafeEqual:', timingSafeEqual(derived, expected));
console.log('derived:', derived.toString('base64url'));
console.log('expected:', hashValue);
